void run_delta_test(int fft_size_bits, const struct fix32_10_Complex *twiddles,
                    int tolerance) {
  struct FFT_Params params = {.fft_size_bits = fft_size_bits};
  size_t fft_size = 1 << fft_size_bits;

  fix32_10 *test_signal = calloc(fft_size, sizeof(fix32_10));
  test_signal[0] = int32_to_fix32_10(1);

  struct fix32_10_Complex *result_freqs =
      calloc(fft_size, sizeof(struct fix32_10_Complex));

  int64_t start_time = esp_timer_get_time();
  generate_result_freqs(&params, twiddles, test_signal, result_freqs);
  int64_t end_time = esp_timer_get_time();

  printf("delta_test_%d us: %lld\n", fft_size_bits, end_time - start_time);

  for (size_t i = 0; i < fft_size; i++) {
    TEST_ASSERT_INT_WITHIN(tolerance, int32_to_fix32_10(1),
                           result_freqs[i].real);
    TEST_ASSERT_INT_WITHIN(tolerance, 0, result_freqs[i].imag);
  }

  free(test_signal);
  free(result_freqs);
}

void run_sine_test(int fft_size_bits, const struct fix32_10_Complex *twiddles,
                   const fix32_10 *test_signal, int tolerance) {
  struct FFT_Params params = {.fft_size_bits = fft_size_bits};
  size_t fft_size = 1 << fft_size_bits;

  struct fix32_10_Complex *result_freqs =
      calloc(fft_size, sizeof(struct fix32_10_Complex));

  int64_t start_time = esp_timer_get_time();
  generate_result_freqs(&params, twiddles, test_signal, result_freqs);
  int64_t end_time = esp_timer_get_time();

  printf("delta_test_%d us: %lld\n", fft_size_bits, end_time - start_time);

  if (fft_size < 32) {
    for (size_t i = 0; i < fft_size; i++) {
      printf("%d: mag %ld \n", i,
             fix32_10_to_int32(multiply_fix32_10(result_freqs[i].real,
                                                 result_freqs[i].real)) +
                 fix32_10_to_int32(multiply_fix32_10(result_freqs[i].imag,
                                                     result_freqs[i].imag)));
    }
  }
  free(result_freqs);
}

